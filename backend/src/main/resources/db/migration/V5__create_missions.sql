CREATE TABLE missions (
    mission_id BIGSERIAL PRIMARY KEY,
    code VARCHAR(80) NOT NULL UNIQUE,
    mission_group VARCHAR(30) NOT NULL,
    mission_type VARCHAR(30) NOT NULL,
    default_status VARCHAR(30) NOT NULL,
    title VARCHAR(120) NOT NULL,
    spot_name VARCHAR(120) NOT NULL,
    city_name VARCHAR(80) NOT NULL,
    description VARCHAR(500) NOT NULL,
    dialogue VARCHAR(500) NOT NULL,
    condition_label VARCHAR(160) NOT NULL,
    reward_type VARCHAR(30) NOT NULL,
    reward_label VARCHAR(120) NOT NULL,
    progress INTEGER NOT NULL DEFAULT 0,
    target INTEGER NOT NULL,
    is_new BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE user_missions (
    user_mission_id BIGSERIAL PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    mission_id BIGINT NOT NULL REFERENCES missions(mission_id),
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_user_missions_user_mission UNIQUE (user_id, mission_id)
);

CREATE INDEX idx_user_missions_user_id ON user_missions(user_id);
CREATE INDEX idx_user_missions_mission_id ON user_missions(mission_id);

