INSERT INTO mission_verification_policies (
    mission_id,
    verification_type,
    expected_answer,
    expected_qr_code,
    required_upload,
    min_step_count,
    created_at,
    updated_at
)
SELECT
    mission_id,
    mission_type,
    NULL,
    NULL,
    mission_type = 'PHOTO',
    CASE WHEN mission_type = 'VISIT_AND_STEP' THEN target ELSE NULL END,
    CURRENT_TIMESTAMP,
    CURRENT_TIMESTAMP
FROM missions
WHERE code IN (
    'MISSION_SOKCHO_YEONGGEUMJEONG_PHOTO',
    'MISSION_DAILY_STEPS_3000',
    'MISSION_DAILY_STEPS_5000'
)
  AND NOT EXISTS (
      SELECT 1
      FROM mission_verification_policies policy
      WHERE policy.mission_id = missions.mission_id
  );
